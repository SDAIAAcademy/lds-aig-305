export function severity(harm, reach) {
  if (!harm) return '';
  const s = harm * reach;
  if (harm === 4 || s >= 12) return 'S1';
  if (s >= 6) return 'S2';
  if (s >= 3) return 'S3';
  return 'S4';
}
